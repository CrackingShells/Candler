"""Regenerate `src/candler_evaluator/_models/` from the published wire schemas.

Run from `python/candler-evaluator`: `uv run --frozen python scripts/gen_models.py`.
One module per schema root: `evaluator-*.schema.json` and `outcome-record.schema.json` of
`crates/candler-schemas/schema/`. Each module's header names its schema file and the file's
sha256, so a changed schema shows as a changed header. The output is deterministic; CI
regenerates it and fails when it differs from what is committed.
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

HELPER = Path(__file__).resolve().parents[1]
SCHEMAS = HELPER.parents[1] / "crates" / "candler-schemas" / "schema"
MODELS = HELPER / "src" / "candler_evaluator" / "_models"

# Options that decide the shape of the output. Formatting is ruff's, so the files pass
# `ruff format --check` as committed.
OPTIONS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.10",
    "--use-annotated",
    "--use-union-operator",
    "--formatters",
    "ruff-check",
    "ruff-format",
]


def roots() -> list[Path]:
    """The schema roots the helper's models come from, in a fixed order."""
    found = sorted(SCHEMAS.glob("evaluator-*.schema.json"))
    found.append(SCHEMAS / "outcome-record.schema.json")
    return found


def module_name(schema: Path) -> str:
    """`evaluator-describe-result.schema.json` becomes `evaluator_describe_result`."""
    return schema.name.removesuffix(".schema.json").replace("-", "_")


def header(schema: Path) -> str:
    """The generated-file header: the schema it comes from and that file's sha256."""
    digest = hashlib.sha256(schema.read_bytes()).hexdigest()
    return (
        "# Generated by scripts/gen_models.py; do not edit.\n"
        f"# schema: crates/candler-schemas/schema/{schema.name}\n"
        f"# sha256: {digest}"
    )


def generate(schema: Path) -> None:
    """Write the module for one schema."""
    out = MODELS / f"{module_name(schema)}.py"
    subprocess.run(
        [
            sys.executable,
            "-W",
            "ignore",
            "-m",
            "datamodel_code_generator",
            "--input",
            str(schema),
            "--output",
            str(out),
            "--custom-file-header",
            header(schema),
            *OPTIONS,
        ],
        check=True,
        cwd=HELPER,
    )


def main() -> int:
    MODELS.mkdir(parents=True, exist_ok=True)
    schemas = roots()
    missing = [s.name for s in schemas if not s.is_file()]
    if missing:
        print(f"missing schema files: {missing}", file=sys.stderr)
        return 1
    wanted = {f"{module_name(s)}.py" for s in schemas} | {"__init__.py"}
    for stale in MODELS.glob("*.py"):
        if stale.name not in wanted:
            stale.unlink()
    (MODELS / "__init__.py").write_text(
        '"""Wire models generated from the published schemas; see scripts/gen_models.py."""\n'
    )
    for schema in schemas:
        generate(schema)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

# /// script
# requires-python = ">=3.11"
# dependencies = ["rfc8785"]
# ///
"""Generate `context_inputs.toml`, the vectors of a run context that serves inputs, with no Candler code.

A run holds each input as store blobs: every file under the sha256 of its bytes, and the input's
list `[{path, sha256}]`, sorted by `path`, under the sha256 of its RFC 8785 form. The input's
digest is the key of the list. A run context serves the inputs a need names, as `{kind, path,
digest}`, and its digest is the sha256 of the RFC 8785 form of
`{artifacts: [], snapshots: [], inputs: [{kind, digest}], metadata: {}}`, the inputs sorted by
`(kind, digest)`. The paths are absolute and local to a request, so they are outside it.

Each vector gives the inputs of a run (`list` says whether the manifest holds the kind in
`comparable.inputs` or in `evaluation_inputs`), the kinds a need names, and the digest of the
context that serves exactly those kinds.

Usage: uv run --with rfc8785 python gen_context_inputs.py          (writes the vectors)
       uv run --with rfc8785 python gen_context_inputs.py --check  (fails if the file differs)
"""

import hashlib
import json
import sys
from pathlib import Path

import rfc8785

OUT = Path(__file__).with_name("context_inputs.toml")

HEADER = """\
# Generated by gen_context_inputs.py; do not edit. Each vector lists the inputs of a run by kind,
# the manifest list that holds the kind, and the files by path and content. `list_json` is the
# RFC 8785 form of the input's sorted `[{path, sha256}]` list, and `digest` its sha256, which is
# the input's digest. `context_digest` is the digest of the context that serves the kinds in
# `needs`, computed by the Python rfc8785 package, which runs no Candler code.
"""


def sha(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def toml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


SERVERS = ("servers", "comparable", [("b/two.txt", "two\n"), ("a.txt", "one\n"), ("données/été.txt", "x\n")])
TRUTH = ("truth", "evaluation", [("reference.json", '{"k": 1}\n')])
BUILD = ("build_inputs", "comparable", [("requirements.txt", "pkg==1\n")])

# (title, inputs the run holds, kinds the need names)
CASES = [
    ("a need for both lists", [SERVERS, TRUTH, BUILD], ["truth", "servers"]),
    ("a need for the evaluator-only input", [SERVERS, TRUTH, BUILD], ["truth"]),
    ("a need for the declared input", [SERVERS, TRUTH, BUILD], ["servers"]),
]


def render_input(kind, lst, files):
    entries = sorted(
        ({"path": p, "sha256": sha(c.encode())} for p, c in files),
        key=lambda e: e["path"].encode("utf-8"),
    )
    canonical = rfc8785.dumps(entries)
    out = [
        "[[vector.input]]",
        f"kind = {toml_str(kind)}",
        f"list = {toml_str(lst)}",
        f"list_json = {toml_str(canonical.decode())}",
        f"digest = {toml_str(sha(canonical))}",
    ]
    for p, c in files:
        out += ["", "[[vector.input.file]]", f"path = {toml_str(p)}", f"content = {toml_str(c)}"]
    return "\n".join(out), sha(canonical)


def render():
    out = [HEADER]
    for title, held, needs in CASES:
        blocks, digests = [], {}
        for kind, lst, files in held:
            block, digests[kind] = render_input(kind, lst, files)
            blocks.append(block)
        served = sorted(({"kind": k, "digest": digests[k]} for k in needs), key=lambda r: (r["kind"], r["digest"]))
        projection = {"artifacts": [], "snapshots": [], "inputs": served, "metadata": {}}
        out.append("[[vector]]")
        out.append(f"title = {toml_str(title)}")
        out.append("needs = [" + ", ".join(toml_str(k) for k in needs) + "]")
        out.append(f"context_digest = {toml_str(sha(rfc8785.dumps(projection)))}")
        out.append("")
        out.append("\n\n".join(blocks))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.name} differs from the generator's output")
        print(f"{OUT.name}: up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.name}")


main()

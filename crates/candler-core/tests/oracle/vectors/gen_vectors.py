def twin(entry, n):
    out = json.loads(jtext(entry))
    out["id"] = entry["id"] + f"-renamed-{n}"
    out["evaluator"] = {"name": "other-eval", "range": ">=1.0.0, <2.0.0"}
    out["deadline_ms"] = 123456 + n
    out["group"] = f"moved-{n}"
    return out



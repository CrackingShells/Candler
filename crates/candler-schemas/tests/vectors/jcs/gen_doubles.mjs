// Writes double-precision samples and their ECMAScript number text, one per line:
//   <16 hex digits of the IEEE 754 bit pattern> TAB <String(x)>
// The committed doubles.tsv comes from `node gen_doubles.mjs` (about 2,000 stratified doubles).
// Larger one-off runs: node gen_doubles.mjs --count 100000 --seed 20261105 --random-only --out /path
// A finite double only: NaN and Infinity have no JSON text.
import { writeFileSync } from "node:fs";
import { argv, version } from "node:process";

const args = Object.fromEntries(
  argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]?.startsWith("--") || all[i + 1] === undefined ? true : all[i + 1]]] : acc), []),
);
const seed = Number(args.seed ?? 8785);
const count = Number(args.count ?? 1000);
const randomOnly = args["random-only"] === true;
const out = args.out ?? new URL("doubles.tsv", import.meta.url).pathname;

function mulberry32(a) {
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(seed);
const view = new DataView(new ArrayBuffer(8));
const toBits = (x) => (view.setFloat64(0, x), view.getBigUint64(0));
const fromBits = (b) => (view.setBigUint64(0, b), view.getFloat64(0));
const finite = (b) => ((b >> 52n) & 0x7ffn) !== 0x7ffn;
const randomBits = () => (BigInt(Math.floor(rand() * 2 ** 32)) << 32n) | BigInt(Math.floor(rand() * 2 ** 32));

const bits = new Set();
const add = (b) => finite(b) && bits.add(b);
const addX = (x) => add(toBits(x));

if (!randomOnly) {
  for (let e = -1074; e <= 1023; e += 2) {
    const x = e < -1022 ? Number.MIN_VALUE * 2 ** (e + 1074) : 2 ** e;
    addX(x);
    if (e % 14 === 0) addX(-x);
  }
  for (let i = 0n; i < 30n; i += 1n) {
    add(i + 1n); // subnormals at the bottom
    add((1n << 52n) - 1n - i); // the largest subnormals
    add((1n << 52n) + i); // the smallest normals
  }
  for (const centre of [1e21, 1e-7, 1e-6, 1e22, 1e23, 2 ** 53, 2 ** 63, 2 ** 64, 0.1, 0.5, 1, 1.5, 123456789.123456789]) {
    for (let d = -8n; d <= 8n; d += 1n) add(toBits(centre) + d), add(toBits(-centre) + d);
  }
  for (const x of [Number.MAX_VALUE, -Number.MAX_VALUE, Number.MIN_VALUE, -Number.MIN_VALUE, Number.EPSILON, 0, -0, Number.MAX_SAFE_INTEGER, -Number.MAX_SAFE_INTEGER, 1e30, 4.5, 0.002, 1e-27, 333333333.33333329]) addX(x);
  for (let k = 0; k < 120; k += 1) {
    addX(Math.pow(10, k - 100));
    addX(Number(`${1 + (k % 9)}e${(k * 7) % 600 - 300}`));
  }
}
while (bits.size < (randomOnly ? count : 2000)) {
  const b = randomBits();
  // random mantissas over normal exponents, and fully random patterns
  add(rand() < 0.5 ? (b & ~(0x7ffn << 52n)) | (BigInt(1 + Math.floor(rand() * 2046)) << 52n) : b);
}

const header = `# Generated by gen_doubles.mjs under Node ${version}: seed ${seed}, ${bits.size} doubles.\n# Columns: IEEE 754 bit pattern (hex) TAB String(x).\n`;
const lines = [...bits].map((b) => `${b.toString(16).padStart(16, "0")}\t${String(fromBits(b))}`);
writeFileSync(out, header + lines.join("\n") + "\n");
console.log(`${out}: ${bits.size} doubles`);

"""Translate the R03 run-config plan `cont-train-version-matrix.yaml` into an experiment file.

The YAML is read with `git show` at the tag `candler-m2a-golden`; the repository is never written.
Usage: uv run translate_run_config.py <r03-repo> > cont_train.toml

Choices that are the translator's, not the YAML's:
- `plan.*` paths follow the importer's convention; `project` and `out_dir` are operational and left out.
- `budget.per_run.wall_s = 3600` is the per-run timeout hard-coded in `run` (CLI_REFERENCE.md).
- the harness is `claude-code` and the treatment `htn-creator`, pinned per cell by the skill_version axis.
"""

import json
import subprocess
import sys

import yaml

TAG = "candler-m2a-golden"
PATH = "harness/evals/plans/cont-train-version-matrix.yaml"


def main(repo: str) -> None:
    text = subprocess.run(
        ["git", "-C", repo, "show", f"{TAG}:{PATH}"],
        check=True, capture_output=True, text=True,
    ).stdout
    plan = yaml.safe_load(text)
    defaults = plan["defaults"]
    prompt = plan["prompts"][defaults["prompt"]]
    domain = plan["domains"][prompt["domain"]]
    axes = plan["matrix"]["axes"]

    q = json.dumps  # a JSON string is a valid TOML basic string for this ASCII text
    out = [f"# Generated by translate_run_config.py from {TAG}:{PATH}", "schema = \"experiment/1\"",
           f"replicates = {defaults['runs']}", "", "[fixed]",
           f"\"plan.config\" = {q(defaults['config'])}",
           f"\"plan.prompt_domain_name\" = {q(domain['prompt_domain_name'])}",
           f"\"plan.prompt_domain_topic\" = {q(domain['prompt_domain_topic'])}",
           f"\"plan.prompt_servers_path\" = {q(prompt['prompt_servers_path'])}", ""]
    for axis, levels in axes.items():
        out.append("[[factors]]")
        out.append(f"path = {q('plan.' + axis)}")
        out.append("levels = [" + ", ".join(q(v) for v in levels) + "]")
        out.append("")
    out += ["[budget.per_run]", "wall_s = 3600", "",
            "[harness]", 'name = "claude-code"', "",
            "[treatment]", 'name = "htn-creator"', ""]
    sys.stdout.write("\n".join(out))


main(sys.argv[1])

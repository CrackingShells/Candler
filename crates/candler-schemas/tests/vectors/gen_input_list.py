# /// script
# requires-python = ">=3.11"
# dependencies = ["rfc8785"]
# ///
"""Generate `input_list_digest.toml`, the vectors of the input-list digest, with no Candler code.

The digest of an input is the sha256 of the RFC 8785 form of its list `[{path, sha256}]`, sorted by
`path` in code point order. A file's `sha256` is the digest of its bytes, written `sha256:<hex>`.
An empty list and a list that repeats a path have no digest.

Usage: uv run --with rfc8785 python gen_input_list.py          (writes the vectors)
       uv run --with rfc8785 python gen_input_list.py --check  (fails if the file differs)
"""

import hashlib
import sys
from pathlib import Path

import rfc8785

OUT = Path(__file__).with_name("input_list_digest.toml")

HEADER = """\
# Generated by gen_input_list.py; do not edit. Each case lists files by path and content; the
# expected digest is the sha256 of the RFC 8785 form of the list [{path, sha256}] sorted by path,
# computed by the Python rfc8785 package, which runs no Candler code. A case with `refused = true`
# has no digest.
"""


def file_digest(content: str) -> str:
    return "sha256:" + hashlib.sha256(content.encode()).hexdigest()


def list_digest(files: list[tuple[str, str]]) -> str:
    entries = sorted(
        ({"path": path, "sha256": file_digest(content)} for path, content in files),
        key=lambda entry: entry["path"],
    )
    return "sha256:" + hashlib.sha256(rfc8785.dumps(entries)).hexdigest()


CASES = [
    ("empty_list", [], True),
    ("one_file", [("reference.json", '{"k": 1}\n')], False),
    (
        "several_files_out_of_order",
        [("b/two.txt", "two\n"), ("a.txt", "one\n"), ("b/one.txt", "three\n"), ("B.txt", "up\n")],
        False,
    ),
    (
        "non_ascii_paths",
        [("données/été.txt", "x\n"), ("日本語.md", "y\n"), ("zebra.txt", "z\n"), ("é.txt", "w\n")],
        False,
    ),
    (
        "code_point_order_differs_from_utf16_order",
        [("a/\U0001f600.txt", "emoji\n"), ("a/\uff5e.txt", "wave\n"), ("a/z.txt", "z\n")],
        False,
    ),
    ("repeated_path", [("a.txt", "one\n"), ("a.txt", "two\n")], True),
]


def toml_string(text: str) -> str:
    out = ['"']
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif char == "\n":
            out.append("\\n")
        else:
            out.append(char)
    out.append('"')
    return "".join(out)


def render() -> str:
    parts = [HEADER]
    for name, files, refused in CASES:
        parts.append(f"\n[[case]]\nname = {toml_string(name)}\n")
        if refused:
            parts.append("refused = true\n")
        else:
            parts.append(f"digest = {toml_string(list_digest(files))}\n")
        for path, content in files:
            parts.append(
                f"[[case.entry]]\npath = {toml_string(path)}\n"
                f"sha256 = {toml_string(file_digest(content))}\n"
            )
    return "".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} differs from the generator", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
